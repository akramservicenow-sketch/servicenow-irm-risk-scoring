#!/usr/bin/env node
'use strict';

/**
 * Generates docs/sample-report.md from the synthetic risk register.
 *
 *   node scripts/generate-report.js [registerJson] [configJson] [outFile]
 *
 * Output is deterministic (dates come from the register's `asOf`), so CI can check
 * that the committed report is up to date.
 */

const fs = require('node:fs');
const path = require('node:path');
const { loadCore } = require('./lib/load-core');

const ROOT = path.join(__dirname, '..');
const registerFile = process.argv[2] || path.join(ROOT, 'data', 'risk-register.json');
const configFile = process.argv[3] || path.join(ROOT, 'config', 'scoring-config.example.json');
const outFile = process.argv[4] || path.join(ROOT, 'docs', 'sample-report.md');

const RiskScoringCore = loadCore();
const register = JSON.parse(fs.readFileSync(registerFile, 'utf8'));
const config = JSON.parse(fs.readFileSync(configFile, 'utf8'));
const core = new RiskScoringCore(config);

const BAND_ICON = { Low: 'L', Moderate: 'M', High: 'H', Critical: 'C' };

const assessments = register.risks.map((risk) => ({
  risk,
  result: core.assess({
    id: risk.id,
    likelihood: risk.likelihood,
    impact: risk.impact,
    category: risk.category,
    controls: risk.controls,
    assessedOn: register.asOf,
  }),
}));

function fmt(n) {
  return Number.isInteger(n) ? String(n) : n.toFixed(2);
}

/** Text heat map: rows = likelihood (high to low), columns = impact (low to high). */
function heatMap() {
  const grid = core.heatMap(assessments.map((a) => a.result));
  const L = core.config.likelihoodLabels;
  const I = core.config.impactLabels;
  const lines = [];
  const colW = 17;
  const header = ''.padEnd(22) + I.map((label, i) => `${i + 1} ${label}`.padEnd(colW)).join('');
  lines.push(header.trimEnd());
  for (let l = L.length; l >= 1; l--) {
    let row = `${l} ${L[l - 1]}`.padEnd(22);
    for (let i = 1; i <= I.length; i++) {
      const score = core.cellScore(l, i);
      const count = grid[l - 1][i - 1];
      const cell = `${BAND_ICON[core.rating(score)]}${String(score).padStart(2)}${count ? ` [${count}]` : ''}`;
      row += cell.padEnd(colW);
    }
    lines.push(row.trimEnd());
  }
  return lines.join('\n');
}

function bandDistribution() {
  const names = core.config.bands.map((b) => b.name);
  const rows = names.map((name) => {
    const inh = assessments.filter((a) => a.result.inherent.rating === name).length;
    const res = assessments.filter((a) => a.result.residual.rating === name).length;
    return `| ${name} | ${inh} | ${res} | ${'#'.repeat(inh).padEnd(8)} -> ${'#'.repeat(res)} |`;
  });
  return ['| Rating | Inherent | Residual | Shift |', '|---|---:|---:|---|', ...rows].join('\n');
}

function riskTable() {
  const sorted = assessments.slice().sort((a, b) => b.result.residual.score - a.result.residual.score || a.risk.id.localeCompare(b.risk.id));
  const rows = sorted.map(({ risk, result }) => {
    return `| ${risk.id} | ${risk.title} | ${risk.category} | ${result.inherent.likelihood}x${result.inherent.impact} = ${result.inherent.score} (${result.inherent.rating}) | ${Math.round(result.controlEffectiveness.applied * 100)}% (${result.controlEffectiveness.count}) | ${fmt(result.residual.score)} (${result.residual.rating}) | ${result.appetite.status} | ${result.reviewDueDate} |`;
  });
  return [
    '| ID | Risk | Category | Inherent (L x I) | Control effectiveness (controls) | Residual | Appetite | Next review |',
    '|---|---|---|---|---:|---|---|---|',
    ...rows,
  ].join('\n');
}

function entityTable() {
  const rows = register.entities.map((entity) => {
    const risks = assessments
      .filter((a) => a.risk.entity === entity.id)
      .map((a) => ({ id: a.risk.id, residualScore: a.result.residual.score, weight: a.risk.weight }));
    const max = core.aggregate(risks, 'max');
    const wavg = core.aggregate(risks, 'weighted_average');
    return `| ${entity.name} | ${risks.length} | ${fmt(max.score)} (${max.rating}, driver ${max.driverId}) | ${fmt(wavg.score)} (${wavg.rating}) |`;
  });
  return ['| Entity | Risks | Max residual | Weighted average residual |', '|---|---:|---|---|', ...rows].join('\n');
}

function breaches() {
  const list = assessments.filter((a) => a.result.appetite.status !== 'Within Appetite');
  if (list.length === 0) return '_No risks above appetite._';
  return list
    .sort((a, b) => b.result.residual.score - a.result.residual.score)
    .map(
      ({ risk, result }) =>
        `- **${risk.id}** ${risk.title}: residual ${fmt(result.residual.score)} vs appetite ${result.appetite.appetite} / tolerance ${result.appetite.tolerance} (${risk.category}) - **${result.appetite.status}**`
    )
    .join('\n');
}

const report = `# Sample Risk Report

> Generated by \`scripts/generate-report.js\` from the **synthetic** register in \`data/risk-register.json\`
> using \`config/scoring-config.example.json\`. Assessment date: ${register.asOf}. All entities, risks and controls are fictional.

## Summary

- Risks assessed: **${assessments.length}** across **${register.entities.length}** entities
- Inherent Critical/High: **${assessments.filter((a) => ['Critical', 'High'].includes(a.result.inherent.rating)).length}**; residual Critical/High: **${assessments.filter((a) => ['Critical', 'High'].includes(a.result.residual.rating)).length}**
- Above appetite: **${assessments.filter((a) => a.result.appetite.status !== 'Within Appetite').length}** (exceeding tolerance: **${assessments.filter((a) => a.result.appetite.status === 'Exceeds Tolerance').length}**)

## Inherent heat map

Each cell shows the rating band (L/M/H/C), the cell score, and in brackets the number of risks in that cell.

\`\`\`text
${heatMap()}
\`\`\`

## Rating distribution (inherent vs residual)

${bandDistribution()}

## Risks above appetite

${breaches()}

## Risk register

${riskTable()}

## Entity roll-up

${entityTable()}
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, report);
console.log(`Report written to ${path.relative(process.cwd(), outFile)}`);
